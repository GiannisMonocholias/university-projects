#===============================
# Α ερώτημα
#===============================
n1 <- 30; x1 <- 12   # άνδρες
n2 <- 30; x2 <- 14   # γυναίκες

p1 <- x1 / n1
p2 <- x2 / n2
p_hat <- (x1 + x2) / (n1 + n2)  # pooled

z <- (p1 - p2) / sqrt(p_hat * (1 - p_hat) * (1/n1 + 1/n2))
p_value <- 2 * (1 - pnorm(abs(z)))

cat("ΑΣΚΗΣΗ 3\n")
cat("\nΑ ερώτημα\n\n")
cat("H0: p1 = p2  (δίπλευρος έλεγχος)\n")
cat("n1 =", n1, ", x1 =", x1, ", p1 =", round(p1, 4), "\n")
cat("n2 =", n2, ", x2 =", x2, ", p2 =", round(p2, 4), "\n")
cat("p_hat =", round(p_hat, 4), "\n")
cat("z =", round(z, 3), "\n")
cat("p_value =", p_value, "\n")

alpha <- 1 - 0.95
z_star <- qnorm(1 - alpha/2)

diff <- p1 - p2
SE <- sqrt((p1 * (1 - p1) / n1) + (p2 * (1 - p2) / n2))

CI_lower <- diff - z_star * SE
CI_upper <- diff + z_star * SE

#===============================
# Β ερώτημα
#===============================
cat("\nΒ ερώτημα\n\n")
cat("95% Διάστημα Εμπιστοσύνης για (p1 - p2)\n")
cat("z* =", z_star, "\n")
cat("CI = [", CI_lower, ", ", CI_upper, "]\n\n", sep = "")

