obs <- matrix(c(12, 18,
                14, 16),
              nrow = 2, byrow = TRUE)

rownames(obs) <- c("Ανδρες", "Γυναικες")
colnames(obs) <- c("Καπνιστες", "Μη_Καπνιστες")

cat("Πίνακας παρατηρούμενων τιμών\n")
print(obs)
cat("\n")

row_tot <- rowSums(obs)
col_tot <- colSums(obs)
N <- sum(obs)

exp <- outer(row_tot, col_tot) / N

cat("Πίνακας αναμενόμενων τιμών\n")
print(exp)
cat("\n")

chi2_stat <- sum((obs - exp)^2 / exp)
df <- 1
p_value <- 1 - pchisq(chi2_stat, df)

cat("Τιμή στατιστικού ελέγχου χ^2\n")
cat("X^2 =", chi2_stat, "\n")
cat("p_value =", p_value, "\n")


